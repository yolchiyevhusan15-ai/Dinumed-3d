// Runs every asset through three.js r187 (vendored) in headless Chromium with ALL
// non-local network requests blocked, then also loads the demo page.
// Usage: node tests/threejs-test.mjs        (needs the `playwright` package + Chromium)
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { createServer } from '../tools/serve.mjs';

const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); } catch {
  ({ chromium } = require(require.resolve('playwright', { paths: ['/opt/node-tools/node_modules'] })));
}
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 8765;
const server = createServer().listen(PORT, '127.0.0.1');
const external = [];
const errors = [];
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1000, height: 800 } });
await ctx.route('**/*', (route) => {
  const u = new URL(route.request().url());
  if (u.hostname === '127.0.0.1' || u.hostname === 'localhost') return route.continue();
  external.push(route.request().url());
  return route.abort();
});
const page = await ctx.newPage();
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });

console.log('running asset checks…');
const t0 = Date.now();
await page.goto(`http://127.0.0.1:${PORT}/tests/threejs-test.html`);
const res = await page.evaluate(() => window.__results);
if (res.error) { console.error(res.error); }
// garderob (shop) smoke test: both genders render, a purchase works, thumbnails are generated
const demo = [];
for (const g of ['male', 'female']) {
  await page.goto(`http://127.0.0.1:${PORT}/demo/?fresh=1&gender=${g}&cam=front&t=2`);
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
  await page.waitForFunction(() => window.__thumbsReady === true, null, { timeout: 180000 });
  await page.waitForTimeout(400);
  const before = await page.evaluate(() => ({ balance: window.__state.balance, worn: window.__state.worn.length }));
  await page.click('.card[data-id="scrub_teal"] .buy');
  await page.waitForFunction(() => window.__state.worn.includes('scrub_teal'), null, { timeout: 30000 });
  await page.waitForTimeout(600);
  const stats = await page.evaluate(() => {
    const c = document.querySelector('#stage canvas');
    const x = document.createElement('canvas'); x.width = 64; x.height = 64;
    const k = x.getContext('2d'); k.drawImage(c, 0, 0, 64, 64);
    const d = k.getImageData(0, 0, 64, 64).data; let mn = 255 * 4, mx = 0;
    for (let i = 0; i < d.length; i += 4) { const v = d[i] + d[i + 1] + d[i + 2] + d[i + 3]; mn = Math.min(mn, v); mx = Math.max(mx, v); }
    return { contrast: mx - mn, balance: window.__state.balance, worn: window.__state.worn.length,
             thumbs: document.querySelectorAll('.thumb img').length, cards: document.querySelectorAll('.card').length };
  });
  demo.push({ gender: g, before, ...stats });
}
await browser.close();
server.close();

const checks = res.checks || [];
checks.push({ name: 'no network request left the machine (offline)', pass: external.length === 0, detail: external.join(', ') });
checks.push({ name: 'no page / console errors', pass: errors.length === 0, detail: errors.join(' | ') });
for (const d of demo) {
  checks.push({ name: `garderob renders ${d.gender} avatar (non-blank canvas, ${d.worn} items worn)`, pass: d.contrast > 100 && d.worn >= 8, detail: `contrast ${d.contrast}` });
  checks.push({ name: `garderob ${d.gender}: buying an item deducts DC and wears it`, pass: d.balance === d.before.balance - 80, detail: `${d.before.balance} -> ${d.balance} DC` });
  checks.push({ name: `garderob ${d.gender}: every shop card has a rendered thumbnail`, pass: d.thumbs === d.cards && d.cards > 15, detail: `${d.thumbs}/${d.cards}` });
}
const passed = !res.error && checks.every((c) => c.pass);
const report = { date: new Date().toISOString(), three: res.info && res.info.three, passed, seconds: (Date.now() - t0) / 1000,
  checks, clipping: res.clipping, contact: res.contact, external, errors };
fs.writeFileSync(path.join(ROOT, 'tests', 'report.json'), JSON.stringify(report, null, 2));

// markdown summary
const mm = (x) => (x * 1000).toFixed(1);
let md = `# DINUMED three.js test report\n\nGenerated by \`node tests/threejs-test.mjs\` (three.js r${report.three}, headless Chromium, external network blocked).\n\n`;
md += `**Result: ${passed ? 'ALL CHECKS PASSED' : 'FAILURES PRESENT'}** (${checks.filter((c) => c.pass).length}/${checks.length} checks)\n\n`;
md += `## Checks\n\n| Result | Check | Detail |\n|---|---|---|\n` + checks.map((c) => `| ${c.pass ? 'PASS' : '**FAIL**'} | ${c.name} | ${(c.detail || '').toString().replace(/\|/g, '/').slice(0, 300)} |`).join('\n');
md += `\n\n## Clipping (penetration > 1 mm), worst over all poses\n\nPoses: bind pose + idle animation sampled every 1 s.\n\n| Gender | Outer | Inner | Vertices tested (bind) | Penetrating (bind) | Penetrating (worst frame) | Max depth mm (all frames) |\n|---|---|---|---|---|---|---|\n`;
const key = (c) => `${c.gender}|${c.outer}|${c.inner}`;
const groups = new Map();
for (const c of res.clipping || []) { if (!groups.has(key(c))) groups.set(key(c), []); groups.get(key(c)).push(c); }
for (const [, arr] of groups) {
  const b = arr.find((c) => c.pose === 'bind');
  const worst = arr.reduce((a, c) => (c.count > a.count ? c : a), arr[0]);
  const maxd = Math.max(...arr.map((c) => c.maxDepth));
  md += `| ${b.gender} | ${b.outer} | ${b.inner} | ${b.tested} | ${b.count} | ${worst.count}${worst.count ? ' (' + worst.pose + ')' : ''} | ${mm(maxd)} |\n`;
}
md += `\n## Accessory contact (minimum distance to support)\n\n| Gender | Pose | Accessory | Supports | Min distance mm | Result |\n|---|---|---|---|---|---|\n`;
for (const c of res.contact || []) md += `| ${c.gender} | ${c.pose} | ${c.accessory} | ${c.supports.join(', ')} | ${mm(c.minDistance)} | ${c.pass ? 'PASS' : 'FAIL'} |\n`;
fs.writeFileSync(path.join(ROOT, 'tests', 'REPORT.md'), md);
for (const c of checks) console.log((c.pass ? 'PASS ' : 'FAIL ') + c.name + (c.pass || !c.detail ? '' : '  [' + c.detail.toString().slice(0, 400) + ']'));
console.log(passed ? '\nALL CHECKS PASSED' : '\nFAILURES PRESENT', `(${report.seconds.toFixed(0)} s)  -> tests/REPORT.md`);
process.exit(passed ? 0 : 1);
